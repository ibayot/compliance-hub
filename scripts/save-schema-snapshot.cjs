// Save a full DDL schema snapshot from all 3 live databases
// Run: node scripts/save-schema-snapshot.cjs
const mysql = require('../backend/node_modules/mysql2/promise');
const fs = require('fs');
const path = require('path');

const DB = {
  host: process.env.DB_HOST || '127.0.0.1',
  port: Number(process.env.DB_PORT || 3306),
  user: process.env.DB_USER || process.env.DB_USERNAME || 'ricms_user',
  password: process.env.DB_PASSWORD || 'ricms_password',
};
const DBS = ['compliance_hub', 'compliance_hub_users', 'compliance_hub_ticketing'];

(async () => {
  const date = new Date().toISOString().slice(0, 10);
  const snapshotDir = path.join(__dirname, '..', 'backend', 'database', 'schema-savepoints');
  fs.mkdirSync(snapshotDir, { recursive: true });
  const outFile = path.join(snapshotDir, date + '-v0.0.49-snapshot.sql');

  let out = '-- Schema Snapshot\n';
  out += '-- Date: ' + date + '\n';
  out += '-- Version: v0.0.49 (before ALTER TABLE migration)\n';
  out += '-- Generated by: scripts/save-schema-snapshot.cjs\n';
  out += '-- USE: Restore with mysql -u <user> -p < this_file\n\n';

  for (const db of DBS) {
    const conn = await mysql.createConnection({ ...DB, database: db });
    const [tbls] = await conn.query(
      'SELECT table_name, table_type FROM information_schema.tables WHERE table_schema = ? ORDER BY table_type DESC, table_name',
      [db]
    );
    out += '\n-- ==========================================\n';
    out += '-- DATABASE: ' + db + '\n';
    out += '-- ==========================================\n\n';
    out += 'CREATE DATABASE IF NOT EXISTS `' + db + '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n';
    out += 'USE `' + db + '`;\n\n';

    for (const row of tbls) {
      const name = row.table_name || row.TABLE_NAME;
      const type = (row.table_type || row.TABLE_TYPE);
      try {
        const [ddlRows] = await conn.query('SHOW CREATE TABLE `' + name + '`');
        const ddl = ddlRows[0]['Create Table'] || ddlRows[0]['Create View'];
        out += '-- ' + type + ': ' + name + '\n';
        if (type === 'VIEW') {
          out += 'DROP VIEW IF EXISTS `' + name + '`;\n';
        } else {
          out += 'DROP TABLE IF EXISTS `' + name + '`;\n';
        }
        out += ddl + ';\n\n';
      } catch (e) {
        out += '-- FAILED to dump ' + name + ': ' + e.message + '\n\n';
      }
    }
    await conn.end();
  }

  fs.writeFileSync(outFile, out, 'utf8');
  console.log('Schema snapshot saved to:', outFile);
  console.log('File size:', Math.round(fs.statSync(outFile).size / 1024), 'KB');
})().catch(e => { console.error('Fatal:', e.message); process.exit(1); });
